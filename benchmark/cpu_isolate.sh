#!/usr/bin/env bash
# Host-level CPU isolation for benchmarks on shared machines.
# Prevents other users' processes from being scheduled on benchmark CPUs.
# Requires root/sudo.
set -euo pipefail

RESTORE_FILE="/tmp/cpu_isolate_restore.sh"
LOCK_FILE="/tmp/cpu_isolate.lock"

usage() {
    echo "Usage:"
    echo "  $0 setup --nodes=N --cpus-per-validator=C [--numa-node-cpus=32] [--num-executors=0]"
    echo "  $0 teardown"
    exit 1
}

# Replicate CPU range formula from docker_bench.py:213-345.
# Returns BENCH_CPUS and SYSTEM_CPUS as global vars.
compute_cpu_ranges() {
    local nodes=$1 cpv=$2 nnc=$3 num_exec=$4
    local total_cpus
    total_cpus=$(nproc)

    if (( nnc > 0 )); then
        # NUMA-aware mode: skip NUMA node 0 (system/Docker overhead)
        local per_numa=$((nnc / cpv))
        local client_numa=$((1 + (nodes + per_numa - 1) / per_numa))
        local bench_start=$nnc
        local bench_end=$(( (client_numa + 1) * nnc - 1 ))

        if (( num_exec > 0 )); then
            bench_end=$(( (client_numa + 2) * nnc - 1 ))
        fi

        BENCH_CPUS="${bench_start}-${bench_end}"
        SYSTEM_CPUS="0-$((nnc - 1))"
    else
        # Simple mode: validators from 0
        local bench_end=$(( nodes * cpv + 2 * nodes - 1 ))
        if (( num_exec > 0 )); then
            local exec_cpus_per=6
            local exec_end=$(( nodes * cpv + 2 * nodes + nodes * num_exec * exec_cpus_per - 1 ))
            (( exec_end > bench_end )) && bench_end=$exec_end
        fi

        BENCH_CPUS="0-${bench_end}"
        SYSTEM_CPUS="$((bench_end + 1))-$((total_cpus - 1))"
    fi

    # Validate range exists on this host
    local max_cpu=$((total_cpus - 1))
    local bench_hi=${BENCH_CPUS##*-}
    if (( bench_hi > max_cpu )); then
        echo "ERROR: benchmark needs CPUs up to $bench_hi but host only has 0-$max_cpu" >&2
        exit 1
    fi
}

do_setup() {
    local nodes=0 cpv=0 nnc=32 num_exec=0
    for arg in "$@"; do
        case "$arg" in
            --nodes=*)              nodes=${arg#*=} ;;
            --cpus-per-validator=*) cpv=${arg#*=} ;;
            --numa-node-cpus=*)     nnc=${arg#*=} ;;
            --num-executors=*)      num_exec=${arg#*=} ;;
            *) echo "Unknown arg: $arg" >&2; usage ;;
        esac
    done
    (( nodes > 0 ))  || { echo "ERROR: --nodes required and must be > 0" >&2; exit 1; }
    (( cpv > 0 ))    || { echo "ERROR: --cpus-per-validator required and must be > 0" >&2; exit 1; }

    if [[ -f "$LOCK_FILE" ]]; then
        echo "ERROR: $LOCK_FILE exists — teardown previous isolation first" >&2
        exit 1
    fi

    compute_cpu_ranges "$nodes" "$cpv" "$nnc" "$num_exec"
    echo "Benchmark CPUs: $BENCH_CPUS"
    echo "System CPUs:    $SYSTEM_CPUS"

    # Save restore state
    {
        echo "#!/usr/bin/env bash"
        echo "# Auto-generated by cpu_isolate.sh setup — do not edit"

        # Save CPU governors
        local bench_lo=${BENCH_CPUS%%-*}
        local bench_hi=${BENCH_CPUS##*-}
        for ((cpu=bench_lo; cpu<=bench_hi; cpu++)); do
            local gov_file="/sys/devices/system/cpu/cpu${cpu}/cpufreq/scaling_governor"
            if [[ -f "$gov_file" ]]; then
                echo "echo '$(cat "$gov_file")' > $gov_file 2>/dev/null || true"
            fi
        done

        # Save turbo boost state
        if [[ -f /sys/devices/system/cpu/intel_pstate/no_turbo ]]; then
            echo "echo '$(cat /sys/devices/system/cpu/intel_pstate/no_turbo)' > /sys/devices/system/cpu/intel_pstate/no_turbo 2>/dev/null || true"
        elif [[ -f /sys/devices/system/cpu/cpufreq/boost ]]; then
            echo "echo '$(cat /sys/devices/system/cpu/cpufreq/boost)' > /sys/devices/system/cpu/cpufreq/boost 2>/dev/null || true"
        fi

        # Save irqbalance state
        if systemctl is-active irqbalance &>/dev/null; then
            echo "systemctl start irqbalance 2>/dev/null || true"
        fi
    } > "$RESTORE_FILE"
    chmod +x "$RESTORE_FILE"

    # 1. Systemd slice shielding: move all userspace off benchmark CPUs
    echo "Shielding benchmark CPUs from other processes..."
    systemctl set-property user.slice AllowedCPUs="$SYSTEM_CPUS"
    systemctl set-property system.slice AllowedCPUs="$SYSTEM_CPUS"

    # 2. CPU frequency governor -> performance
    echo "Setting CPU governor to performance on benchmark CPUs..."
    local bench_lo=${BENCH_CPUS%%-*}
    local bench_hi=${BENCH_CPUS##*-}
    for ((cpu=bench_lo; cpu<=bench_hi; cpu++)); do
        local gov_file="/sys/devices/system/cpu/cpu${cpu}/cpufreq/scaling_governor"
        if [[ -f "$gov_file" ]]; then
            echo performance > "$gov_file" 2>/dev/null || true
        fi
    done

    # 3. Disable turbo boost for thermal consistency
    echo "Disabling turbo boost..."
    if [[ -f /sys/devices/system/cpu/intel_pstate/no_turbo ]]; then
        echo 1 > /sys/devices/system/cpu/intel_pstate/no_turbo
    elif [[ -f /sys/devices/system/cpu/cpufreq/boost ]]; then
        echo 0 > /sys/devices/system/cpu/cpufreq/boost
    else
        echo "  (no turbo boost control found, skipping)"
    fi

    # 4. Pin IRQs to system CPUs
    echo "Pinning IRQs to system CPUs..."
    systemctl stop irqbalance 2>/dev/null || true
    for irq_dir in /proc/irq/[0-9]*/; do
        echo "$SYSTEM_CPUS" > "${irq_dir}smp_affinity_list" 2>/dev/null || true
    done

    touch "$LOCK_FILE"
    echo "CPU isolation active."
}

do_teardown() {
    echo "Tearing down CPU isolation..."

    # Reset systemd slices (empty = all CPUs)
    systemctl set-property user.slice AllowedCPUs="" 2>/dev/null || true
    systemctl set-property system.slice AllowedCPUs="" 2>/dev/null || true

    # Restore saved state
    if [[ -f "$RESTORE_FILE" ]]; then
        source "$RESTORE_FILE"
        rm -f "$RESTORE_FILE"
    fi

    rm -f "$LOCK_FILE"
    echo "CPU isolation removed."
}

[[ $# -ge 1 ]] || usage
case "$1" in
    setup)    shift; do_setup "$@" ;;
    teardown) do_teardown ;;
    *)        usage ;;
esac
